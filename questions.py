def is_math_image(text: str) -> bool:
    """Определяет, стоит ли рисовать вопрос картинкой."""
    if len(text) > 60:
        return False
    math_chars = set("0123456789+-*/=×÷()?")
    total = len(text.replace(" ", ""))
    if total == 0:
        return False
    math_count = sum(1 for c in text if c in math_chars)
    return math_count / total > 0.5


def random_question():
    """Возвращает (вопрос, [ответы], is_multi, is_image)."""
    import random
    # 15% — мультиответ
    if random.random() < 0.15 and MULTI_QUESTIONS:
        q, answers = random.choice(MULTI_QUESTIONS)
        return q, [a.lower() for a in answers], True, False
    # обычный
    q, answers = random.choice(QUESTIONS)
    return q, [a.lower() for a in answers], False, is_math_image(q)
