def random_question(difficulty: str = "medium"):
    """Возвращает (вопрос, [ответы], is_multi, is_image)."""
    import random

    pools = {
        "easy": EASY_QUESTIONS,
        "medium": MEDIUM_QUESTIONS,
        "hard": HARD_QUESTIONS,
        "extreme": EXTREME_QUESTIONS,
        "any": EASY_QUESTIONS + MEDIUM_QUESTIONS + HARD_QUESTIONS,
    }
    pool = pools.get(difficulty) or MEDIUM_QUESTIONS
    q, answers = random.choice(pool)

    # картинка, если много цифр
    math_chars = set("0123456789+-*/=×÷()?")
    total = len(q.replace(" ", ""))
    is_image = total > 0 and sum(1 for c in q if c in math_chars) / total > 0.5

    return q, [a.lower() for a in answers], False, is_image


